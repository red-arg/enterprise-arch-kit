#!/usr/bin/env python3
"""Generate Claude Code and Codex packages from the shared source in src/.

    python3 build.py           # write dist/claude and dist/codex
    python3 build.py --check   # exit 1 if dist/ is out of date (for CI)

Source layout
  src/skills/<name>/SKILL.md (+ references/, scripts/, assets/)
      Agent Skills standard — identical for both tools. Markdown files may
      contain {{#claude}}…{{/claude}} and {{#codex}}…{{/codex}} blocks.
  src/agents/<name>/agent.toml + prompt.md
      Neutral agent definition rendered to each tool's native format.
  src/instructions/AGENTS.md
      Project instructions block (CLAUDE.md for Claude Code, AGENTS.md for Codex).

Output layout (mirrors where files go in a project)
  dist/claude/.claude/agents/*.md      dist/codex/.codex/agents/*.toml
  dist/claude/.claude/skills/*/        dist/codex/.agents/skills/*/
  dist/claude/CLAUDE.md                dist/codex/AGENTS.md

Standard library only. Python 3.11+.
"""
from __future__ import annotations

import filecmp
import json
import re
import shutil
import sys
import tempfile
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SRC = ROOT / "src"
DIST = ROOT / "dist"
PLATFORMS = ("claude", "codex")
BANNER = "Generated by enterprise-arch-kit build.py from src/. Edit the source, not this file."

SKILL_NAME_RE = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
AGENT_NAME_RE = re.compile(r"^[a-z][a-z0-9_]*$")
CLAUDE_TOOLS = {"Read", "Write", "Edit", "Grep", "Glob", "Bash", "WebFetch", "WebSearch",
                "NotebookEdit", "TodoWrite", "Skill", "Agent", "LSP", "PowerShell"}
CLAUDE_MODELS = {"inherit", "sonnet", "opus", "haiku", "fable"}
CLAUDE_EFFORT = {"low", "medium", "high", "xhigh", "max"}
CODEX_SANDBOX = {"read-only", "workspace-write", "danger-full-access"}
CODEX_EFFORT = {"minimal", "low", "medium", "high", "xhigh", "max", "ultra"}


SKILL_LOCATION = {
    "claude": ("Skill files: each skill's folder is `.claude/skills/<skill-name>/` in this project "
               "(or `~/.claude/skills/<skill-name>/` if installed for the user). When a skill "
               "mentions `references/…`, `assets/…` or `scripts/…`, read them from that folder."),
    "codex": ("Skill files: each skill's folder is `.agents/skills/<skill-name>/` in this repository "
              "(or `~/.agents/skills/<skill-name>/` for the user). When a skill mentions "
              "`references/…`, `assets/…` or `scripts/…`, read them from that folder."),
}


class BuildError(Exception):
    pass


# ------------------------------------------------------------------ helpers
def render(text: str, platform: str) -> str:
    """Keep {{#platform}} blocks for this platform, drop the others."""
    for p in PLATFORMS:
        pattern = re.compile(r"\{\{#" + p + r"\}\}\n?(.*?)\{\{/" + p + r"\}\}\n?", re.S)
        text = pattern.sub((lambda m: m.group(1)) if p == platform else "", text)
    if "{{#" in text or "{{/" in text:
        raise BuildError("unbalanced platform block")
    return text


def frontmatter(text: str) -> dict[str, str]:
    """Minimal parser for simple `key: value` SKILL.md frontmatter."""
    if not text.startswith("---\n"):
        raise BuildError("missing frontmatter")
    end = text.index("\n---", 4)
    out = {}
    for line in text[4:end].splitlines():
        if ":" in line and not line.startswith((" ", "\t")):
            k, v = line.split(":", 1)
            out[k.strip()] = v.strip().strip('"').strip("'")
    return out


def yaml_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)  # JSON strings are valid YAML double-quoted scalars


def toml_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)  # JSON strings are valid TOML basic strings


def toml_multiline(s: str) -> str:
    s = s.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    return '"""\n' + s.rstrip("\n") + '\n"""'


# ------------------------------------------------------------------ skills
def tech_stack_markdown(stack: dict) -> str:
    lines = [
        "# Approved tech stack",
        "",
        f"<!-- {BANNER} Source: references/stack.json -->",
        "",
        f"Owner: {stack.get('owner', 'TODO')} · Version {stack.get('version', '?')} · "
        f"Last reviewed: {stack.get('last_reviewed', 'TODO')}",
        "",
        "> TODO(architecture-team): illustrative defaults. Edit `stack.json`, not this file.",
        "",
        "Statuses: **adopt** (default) · **trial** (allowed, needs owner) · "
        "**hold** (no new usage) · **retire** (remove) · **local** (local adapters and tests only, PAT-19) · "
        "unlisted = unassessed.",
        "",
        "## Technologies",
        "",
        "| ID | Category | Technology | Status | Notes |",
        "| --- | --- | --- | --- | --- |",
    ]
    for t in stack["technologies"]:
        lines.append(f"| {t['id']} | {t['category']} | {t['name']} | {t['status']} | {t.get('notes', '')} |")
    lines += ["", "## Packages by ecosystem", "",
              "Names support `*` wildcards. Run the `stack-check` skill's script to audit a repo.", ""]
    for eco, statuses in stack["packages"].items():
        if not any(statuses.values()):
            continue
        lines += [f"### {eco}", ""]
        for status in ("adopt", "trial", "local", "hold", "retire"):
            names = statuses.get(status, [])
            if names:
                lines.append(f"- **{status}:** " + ", ".join(f"`{n}`" for n in names))
        lines.append("")
    return "\n".join(lines)


def validate_stack(stack: dict) -> None:
    valid = {"adopt", "trial", "hold", "retire", "local"}
    ids = set()
    for t in stack["technologies"]:
        if t["status"] not in valid:
            raise BuildError(f"stack.json: {t['id']} has invalid status {t['status']!r}")
        if t["id"] in ids:
            raise BuildError(f"stack.json: duplicate id {t['id']}")
        ids.add(t["id"])
    for eco, statuses in stack["packages"].items():
        seen: dict[str, str] = {}
        for status, names in statuses.items():
            if status not in valid:
                raise BuildError(f"stack.json: packages.{eco} has invalid status {status!r}")
            for n in names:
                if n in seen:
                    raise BuildError(f"stack.json: {eco} package {n!r} listed as both {seen[n]} and {status}")
                seen[n] = status


def build_skills(out: Path, platform: str) -> list[str]:
    skills_dir = out / (".claude/skills" if platform == "claude" else ".agents/skills")
    names = []
    for src_dir in sorted(p for p in (SRC / "skills").iterdir() if p.is_dir()):
        skill_md = src_dir / "SKILL.md"
        if not skill_md.exists():
            raise BuildError(f"{src_dir} has no SKILL.md")
        fm = frontmatter(skill_md.read_text())
        name, desc = fm.get("name", ""), fm.get("description", "")
        if name != src_dir.name or not SKILL_NAME_RE.match(name) or len(name) > 64:
            raise BuildError(f"{skill_md}: name {name!r} must match folder and be kebab-case ≤64 chars")
        if not desc or len(desc) > 1024 or "<" in desc or ">" in desc:
            raise BuildError(f"{skill_md}: description must be 1–1024 chars without angle brackets")
        dest = skills_dir / name
        for f in sorted(src_dir.rglob("*")):
            if f.is_dir() or "__pycache__" in f.parts:
                continue
            rel = f.relative_to(src_dir)
            if platform == "claude" and rel.parts[0] == "agents":
                continue  # agents/openai.yaml is Codex-only skill metadata
            target = dest / f.relative_to(src_dir)
            target.parent.mkdir(parents=True, exist_ok=True)
            if f.suffix == ".md":
                target.write_text(render(f.read_text(), platform))
            else:
                shutil.copy2(f, target)
        if name == "enterprise-standards":
            stack = json.loads((src_dir / "references" / "stack.json").read_text())
            validate_stack(stack)
            (dest / "references" / "tech-stack.md").write_text(tech_stack_markdown(stack))
        names.append(name)
    return names


# ------------------------------------------------------------------ agents
def load_agents(skill_names: list[str]) -> list[dict]:
    agents = []
    for d in sorted(p for p in (SRC / "agents").iterdir() if p.is_dir()):
        spec = tomllib.loads((d / "agent.toml").read_text())
        spec["prompt"] = (d / "prompt.md").read_text()
        name = spec.get("name", "")
        if name != d.name or not AGENT_NAME_RE.match(name):
            raise BuildError(f"{d}: name {name!r} must match folder and be snake_case")
        if not spec.get("description"):
            raise BuildError(f"{d}: description is required")
        for s in spec.get("skills", []):
            if s not in skill_names:
                raise BuildError(f"{d}: unknown skill {s!r}")
        c, x = spec.get("claude", {}), spec.get("codex", {})
        bad = set(c.get("tools", [])) - CLAUDE_TOOLS
        if bad:
            raise BuildError(f"{d}: unknown Claude tools {sorted(bad)}")
        if c.get("model") and c["model"] not in CLAUDE_MODELS and not c["model"].startswith("claude-"):
            raise BuildError(f"{d}: invalid Claude model {c['model']!r}")
        if c.get("guard") and (c["guard"] not in GUARDS or "tdd" not in spec.get("skills", [])):
            raise BuildError(f"{d}: guard must be one of {sorted(GUARDS)} and the agent needs the tdd skill")
        if c.get("effort") and c["effort"] not in CLAUDE_EFFORT:
            raise BuildError(f"{d}: invalid Claude effort {c['effort']!r}")
        if x.get("sandbox_mode") and x["sandbox_mode"] not in CODEX_SANDBOX:
            raise BuildError(f"{d}: invalid Codex sandbox_mode {x['sandbox_mode']!r}")
        if x.get("model_reasoning_effort") and x["model_reasoning_effort"] not in CODEX_EFFORT:
            raise BuildError(f"{d}: invalid Codex model_reasoning_effort")
        agents.append(spec)
    return agents


GUARDS = {"test-writer", "implementer"}


def guard_command(role: str) -> str:
    """Shell command for a Claude Code PreToolUse hook running the tdd guard.

    Looks for the script in the project, then the user-level install; if it
    isn't there, exits 0 (allow) rather than blocking every tool call."""
    return ('f="$CLAUDE_PROJECT_DIR/.claude/skills/tdd/scripts/tdd_guard.py"; '
            '[ -f "$f" ] || f="$HOME/.claude/skills/tdd/scripts/tdd_guard.py"; '
            '[ -f "$f" ] || exit 0; '
            f'exec python3 "$f" hook {role}')


def claude_agent(spec: dict) -> str:
    c = spec.get("claude", {})
    fm = [f"name: {spec['name']}", f"description: {yaml_str(spec['description'])}"]
    if c.get("tools"):
        fm.append("tools: " + ", ".join(c["tools"]))
    for key in ("model", "effort", "color"):
        if c.get(key):
            fm.append(f"{key}: {c[key]}")
    if spec.get("skills"):
        fm.append("skills:")
        fm += [f"  - {s}" for s in spec["skills"]]
    if c.get("guard"):
        fm += ["hooks:", "  PreToolUse:",
               "    - matcher: \"Read|Grep|Glob|Bash|Write|Edit|MultiEdit|NotebookEdit\"",
               "      hooks:", "        - type: command",
               f"          command: {yaml_str(guard_command(c['guard']))}"]
    body = render(spec["prompt"], "claude").rstrip() + "\n"
    if spec.get("skills"):
        body = (SKILL_LOCATION["claude"] + "\n\n") + body
    return "---\n" + "\n".join(fm) + "\n---\n\n<!-- " + BANNER + " -->\n\n" + body


def codex_agent(spec: dict) -> str:
    x = spec.get("codex", {})
    preamble = ""
    if spec.get("skills"):
        listed = ", ".join(f"`{s}`" for s in spec["skills"])
        preamble = (f"Before you start, load these skills and follow them: {listed} "
                    f"(mention them as {', '.join('$' + s for s in spec['skills'])}).\n"
                    + SKILL_LOCATION["codex"] + "\n\n")
    lines = [f"# {BANNER}",
             f"name = {toml_str(spec['name'])}",
             f"description = {toml_str(spec['description'])}"]
    for key in ("model", "model_reasoning_effort", "sandbox_mode"):
        if x.get(key):
            lines.append(f"{key} = {toml_str(x[key])}")
    lines.append("developer_instructions = " + toml_multiline(preamble + render(spec["prompt"], "codex")))
    text = "\n".join(lines) + "\n"
    tomllib.loads(text)  # fail the build on invalid TOML
    return text


# ------------------------------------------------------------------ build
def build_speckit_preset(out: Path) -> None:
    """Copy the Spec Kit preset verbatim after checking every referenced file exists."""
    src = SRC / "speckit-preset"
    if not src.exists():
        return
    manifest = (src / "preset.yml").read_text()
    for ref in re.findall(r'^\s*file:\s*"?([^"\n]+)"?', manifest, re.M):
        if not (src / ref.strip()).is_file():
            raise BuildError(f"speckit-preset/preset.yml references missing file {ref.strip()}")
    for f in (src / "commands").glob("*.md"):
        text = f.read_text()
        for skill in re.findall(r"`([a-z]+(?:-[a-z]+)+)` skill", text):
            if not (SRC / "skills" / skill).is_dir():
                raise BuildError(f"{f.name} references unknown skill {skill!r}")
    shutil.copytree(src, out / "speckit-preset")


def build(out: Path) -> None:
    if out.exists():
        shutil.rmtree(out)
    for platform in PLATFORMS:
        base = out / platform
        skill_names = build_skills(base, platform)
        agents = load_agents(skill_names)
        instructions = render((SRC / "instructions" / "AGENTS.md").read_text(), platform)
        if platform == "claude":
            agents_dir = base / ".claude" / "agents"
            agents_dir.mkdir(parents=True, exist_ok=True)
            for a in agents:
                (agents_dir / f"{a['name']}.md").write_text(claude_agent(a))
            (base / "CLAUDE.md").write_text(instructions)
        else:
            agents_dir = base / ".codex" / "agents"
            agents_dir.mkdir(parents=True, exist_ok=True)
            for a in agents:
                (agents_dir / f"{a['name']}.toml").write_text(codex_agent(a))
            (base / "AGENTS.md").write_text(instructions)
    build_speckit_preset(out)


def dirs_equal(a: Path, b: Path) -> bool:
    cmp = filecmp.dircmp(a, b)
    if cmp.left_only or cmp.right_only or cmp.funny_files:
        return False
    _, mismatch, errors = filecmp.cmpfiles(a, b, cmp.common_files, shallow=False)
    if mismatch or errors:
        return False
    return all(dirs_equal(a / d, b / d) for d in cmp.common_dirs)


def main() -> int:
    check = "--check" in sys.argv[1:]
    try:
        if check:
            with tempfile.TemporaryDirectory() as tmp:
                build(Path(tmp) / "dist")
                if not DIST.exists() or not dirs_equal(Path(tmp) / "dist", DIST):
                    print("dist/ is out of date. Run: python3 build.py", file=sys.stderr)
                    return 1
            print("dist/ is up to date.")
            return 0
        build(DIST)
    except BuildError as exc:
        print(f"build error: {exc}", file=sys.stderr)
        return 1
    count = lambda p: len(list(p.iterdir()))  # noqa: E731
    print(f"Built dist/claude ({count(DIST/'claude/.claude/agents')} agents, "
          f"{count(DIST/'claude/.claude/skills')} skills) and dist/codex "
          f"({count(DIST/'codex/.codex/agents')} agents, {count(DIST/'codex/.agents/skills')} skills).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
